<?php
//1. Створення базового PHP-скрипта
// Виводимо на екран текст "Hello world!"
echo "Hello world!";
echo "<hr>";

//2. Змінні та типи даних
$name = "Олексій"; // Рядкова змінна
$age = 20; // Цілочисельна змінна
$average = 91.5; // Число з плаваючою комою
$isStudent = true; // Булева змінна

// Виводимо значення змінних
echo "Ім'я: " . $name . "<br>";
echo "Вік: " . $age . "<br>";
echo "Середній бал: " . $average . "<br>";
echo "Студент: " . $isStudent . "<br><br>";

// Виводимо типи змінних за допомогою var_dump()
echo "Тип змінної name: ";
var_dump($name);
echo "<br>Тип змінної age: ";
var_dump($age);
echo "<br>Тип змінної average: ";
var_dump($average);
echo "<br>Тип змінної isStudent: ";
var_dump($isStudent);
echo "<hr>";

//3. Конкатенація рядків
$firstName = "Олексій";
$lastName = "Шевченко";
// Об'єднуємо два рядки
$fullName = $firstName . " " . $lastName;
echo "Повне ім'я: " . $fullName;
echo "<hr>";

//4. Умовні конструкції
$number = 10;
// Перевіряємо, чи є число парним
if ($number % 2 == 0) {
    echo "Число " . $number . " є парним";
} else {
    echo "Число " . $number . " є непарним";
}
echo "<hr>";

//5. Цикли
// Цикл for виводить числа від 1 до 10
echo "Числа від 1 до 10:<br>";
for ($i = 1; $i <= 10; $i++) {
    echo $i . " ";
}
echo "<br><br>";

// Цикл while виводить числа від 10 до 1
echo "Числа від 10 до 1:<br>";
$i = 10;
while ($i >= 1) {
    echo $i . " ";
    $i--;
}
echo "<hr>";

//6. Масиви
// Створюємо асоціативний масив з інформацією про студента
$student = [
    "ім'я" => "Олексій",
    "прізвище" => "Шевченко",
    "вік" => 20,
    "спеціальність" => "Комп'ютерні науки"
];
echo "Ім'я: " . $student["ім'я"] . "<br>";
echo "Прізвище: " . $student["прізвище"] . "<br>";
echo "Вік: " . $student["вік"] . "<br>";
echo "Спеціальність: " . $student["спеціальність"] . "<br>";
// Додаємо середній бал до масиву
$student["середній бал"] = 91.5;
// Виводимо оновлений масив
echo "<br>Оновлений масив студента:<br>";
echo "<pre>";
print_r($student);
echo "</pre>";
?>